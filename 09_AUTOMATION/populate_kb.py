def main():
    # Seguridad: no reconstruir una base que ya tiene contenido.
    if os.path.exists(DB):
        probe = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
        try:
            existing = probe.execute("SELECT COUNT(*) FROM concepts").fetchone()[0]
        except sqlite3.OperationalError:
            existing = 0
        probe.close()
        if existing and os.environ.get("XAVI_ALLOW_REBUILD") != "1":
            raise SystemExit(
                "populate_kb.py es DESTRUCTIVO y la base ya tiene "
                f"{existing} conceptos. No se ejecuta. Usa una migración/merge "
                "o exporta XAVI_ALLOW_REBUILD=1 si de verdad quieres reconstruir."
            )
        if existing:
            backup_dir = os.path.join(BASE, "07_KNOWLEDGE_BASE", "backups")
            os.makedirs(backup_dir, exist_ok=True)
            stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            backup = os.path.join(backup_dir, f"xavi_ruyra_before_populate_{stamp}.db")
            # Copia de fichero, no sqlite3 backup(): en sistemas de ficheros
            # montados (Windows/9p) la API devuelve "disk I/O error".
            probe.close()
            shutil.copy2(DB, backup)
            print(f"Backup previo: {backup}")

    con = connect()
    cur = con.cursor()

    # Rebuild limpio de las tablas de metodología.
    for table in ("evidence", "rules", "concepts", "trades", "changes", "curriculum"):
        cur.execute(f"DELETE FROM {table}")

    concept_ids = {}
    for c in CONCEPTS:
        cur.execute(
            """INSERT INTO concepts
            (name, aliases, category, definition, xavi_interpretation, how_identify,
             when_used, conditions, timeframes, combinations, application,
             common_errors, exceptions, status, certainty, first_seen_video,
             first_seen_ts, last_updated, notes)
            VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
            (
                c["name"], c["aliases"], c["category"], c["definition"],
                c["xavi_interpretation"], c["how_identify"], c["when_used"],
                c["conditions"], c["timeframes"], c["combinations"],
                c["application"], c["common_errors"], c["exceptions"],
                c["status"], c["certainty"], c["first_seen_video"],
                c["first_seen_ts"], TODAY, c["notes"],
            ),
        )
        concept_ids[c["name"]] = cur.lastrowid

    rule_ids = {}
    for r in RULES:
        cur.execute(
            """INSERT INTO rules
            (name, description, context, conditions, confirmations, entry_conditions,
             invalidation, risk_management, targets, exceptions, status, certainty,
             first_seen_video, first_seen_ts, version, supersedes, last_updated, notes)
            VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
            (
                r["name"], r["description"], r["context"], r["conditions"],
                r["confirmations"], r["entry_conditions"], r["invalidation"],
                r["risk_management"], r["targets"], r["exceptions"],
                r["status"], r["certainty"], r["first_seen_video"],
                r["first_seen_ts"], r.get("version", 1), None, TODAY, r["notes"],
            ),
        )
        rule_ids[r["name"]] = cur.lastrowid

    # Resolver supersedes después de tener todos los IDs.
    for r in RULES:
        if r.get("supersedes_name"):
            cur.execute(
                "UPDATE rules SET supersedes=? WHERE id=?",
                (rule_ids[r["supersedes_name"]], rule_ids[r["name"]]),
            )

    for e in EVIDENCE:
        entity_type, entity_name, video_id, ts, quote, source_type, notes = e
        entity_id = concept_ids.get(entity_name) if entity_type == "concept" else rule_ids.get(entity_name)
        if entity_id is None:
            print(f"AVISO: evidencia sin entidad: {entity_type} / {entity_name}")
            continue
        cur.execute(
            """INSERT INTO evidence
            (entity_type, entity_id, video_id, timestamp_sec, frame_id, quote,
             source_type, date, url, notes)
            VALUES (?,?,?,?,?,?,?,?,?,?)""",
            (
                entity_type, entity_id, video_id, ts, None, quote,
                source_type, VIDEO_DATES.get(video_id), url(video_id), notes,
            ),
        )

    for t in TRADES:
        cur.execute(
            """INSERT INTO trades
            (video_id, date, instrument, timeframe, session, context, reasoning,
             setup, entry, stop, target, result, management, post_analysis,
             classification, certainty, notes)
            VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
            (
                t["video_id"], t["date"], t["instrument"], t["timeframe"],
                t["session"], t["context"], t["reasoning"], t["setup"],
                t["entry"], t["stop"], t["target"], t["result"],
                t["management"], t["post_analysis"], t["classification"],
                t["certainty"], t["notes"],
            ),
        )

    for ch in CHANGES:
        entity_id = None
        if ch["entity_type"] == "concept":
            entity_id = concept_ids.get(ch["entity_name"])
        elif ch["entity_type"] == "rule":
            entity_id = rule_ids.get(ch["entity_name"])
        cur.execute(
            """INSERT INTO changes
            (date, entity_type, entity_id, change_type, description,
             old_value, new_value, source_video, source_ts)
            VALUES (?,?,?,?,?,?,?,?,?)""",
            (
                ch["date"], ch["entity_type"], entity_id, ch["change_type"],
                ch["description"], ch["old_value"], ch["new_value"],
                ch["source_video"], ch["source_ts"],
            ),
        )

    for c in CURRICULUM:
        cur.execute(
            """INSERT INTO curriculum
            (order_num, module, lesson, video_id, concepts, status, notes)
            VALUES (?,?,?,?,?,?,?)""",
            (
                c["order_num"], c["module"], c["lesson"], c["video_id"],
                c["concepts"], c["status"], c["notes"],
            ),
        )

    con.commit()

    print("Población completada:")
    for table in ("concepts", "rules", "evidence", "trades", "changes", "curriculum"):
        n = cur.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
        print(f"  {table}: {n}")

    print("\nConceptos por categoría:")
    for row in cur.execute(
        "SELECT category, COUNT(*) FROM concepts GROUP BY category ORDER BY category"
    ):
        print(f"  {row[0]}: {row[1]}")

    print("\nReglas por estado:")
    for row in cur.execute(
        "SELECT status, COUNT(*) FROM rules GROUP BY status ORDER BY status"
    ):
        print(f"  {row[0]}: {row[1]}")

    con.close()


def merge():
    """Inserta solo lo que falta, sin borrar nada.

    Se usa cuando la base ya contiene entidades que no están en este script
    (por ejemplo, reglas añadidas por otras vías). El rebuild destruiría esas
    filas; el merge las conserva y añade las nuevas.
    """
    con = connect()
    cur = con.cursor()
    added = {"concepts": 0, "rules": 0, "evidence": 0, "changes": 0, "curriculum": 0}

    concept_ids = {r[0]: r[1] for r in cur.execute("SELECT name, id FROM concepts")}
    for c in CONCEPTS:
        if c["name"] in concept_ids:
            continue
        cur.execute(
            """INSERT INTO concepts
            (name, aliases, category, definition, xavi_interpretation, how_identify,
             when_used, conditions, timeframes, combinations, application,
             common_errors, exceptions, status, certainty, first_seen_video,
             first_seen_ts, last_updated, notes)
            VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
            (c["name"], c["aliases"], c["category"], c["definition"],
             c["xavi_interpretation"], c["how_identify"], c["when_used"],
             c["conditions"], c["timeframes"], c["combinations"], c["application"],
             c["common_errors"], c["exceptions"], c["status"], c["certainty"],
             c["first_seen_video"], c["first_seen_ts"], TODAY, c["notes"]),
        )
        concept_ids[c["name"]] = cur.lastrowid
        added["concepts"] += 1

    rule_ids = {r[0]: r[1] for r in cur.execute("SELECT name, id FROM rules")}
    for r in RULES:
        if r["name"] in rule_ids:
            continue
        cur.execute(
            """INSERT INTO rules
            (name, description, context, conditions, confirmations, entry_conditions,
             invalidation, risk_management, targets, exceptions, status, certainty,
             first_seen_video, first_seen_ts, version, supersedes, last_updated, notes)
            VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
            (r["name"], r["description"], r["context"], r["conditions"],
             r["confirmations"], r["entry_conditions"], r["invalidation"],
             r["risk_management"], r["targets"], r["exceptions"], r["status"],
             r["certainty"], r["first_seen_video"], r["first_seen_ts"],
             r.get("version", 1), None, TODAY, r["notes"]),
        )
        rule_ids[r["name"]] = cur.lastrowid
        added["rules"] += 1

    existing_ev = set(
        cur.execute("SELECT entity_type, video_id, timestamp_sec, quote FROM evidence")
    )
    for e in EVIDENCE:
        entity_type, entity_name, video_id, ts, quote, source_type, notes = e
        entity_id = concept_ids.get(entity_name) if entity_type == "concept" else rule_ids.get(entity_name)
        if entity_id is None:
            print(f"AVISO: evidencia sin entidad: {entity_type} / {entity_name}")
            continue
        if (entity_type, video_id, ts, quote) in existing_ev:
            continue
        cur.execute(
            """INSERT INTO evidence
            (entity_type, entity_id, video_id, timestamp_sec, frame_id, quote,
             source_type, date, url, notes)
            VALUES (?,?,?,?,?,?,?,?,?,?)""",
            (entity_type, entity_id, video_id, ts, None, quote, source_type,
             VIDEO_DATES.get(video_id), url(video_id), notes),
        )
        added["evidence"] += 1

    existing_ch = set(cur.execute("SELECT date, description FROM changes"))
    for ch in CHANGES:
        if (ch["date"], ch["description"]) in existing_ch:
            continue
        entity_id = None
        if ch["entity_type"] == "concept":
            entity_id = concept_ids.get(ch["entity_name"])
        elif ch["entity_type"] == "rule":
            entity_id = rule_ids.get(ch["entity_name"])
        cur.execute(
            """INSERT INTO changes
            (date, entity_type, entity_id, change_type, description,
             old_value, new_value, source_video, source_ts)
            VALUES (?,?,?,?,?,?,?,?,?)""",
            (ch["date"], ch["entity_type"], entity_id, ch["change_type"],
             ch["description"], ch["old_value"], ch["new_value"],
             ch["source_video"], ch["source_ts"]),
        )
        added["changes"] += 1

    existing_cur = {r[0] for r in cur.execute("SELECT order_num FROM curriculum")}
    for c in CURRICULUM:
        if c["order_num"] in existing_cur:
            continue
        cur.execute(
            """INSERT INTO curriculum
            (order_num, module, lesson, video_id, concepts, status, notes)
            VALUES (?,?,?,?,?,?,?)""",
            (c["order_num"], c["module"], c["lesson"], c["video_id"],
             c["concepts"], c["status"], c["notes"]),
        )
        added["curriculum"] += 1

    con.commit()
    print("Merge completado (sin borrar nada):")
    for k, v in added.items():
        print(f"  {k}: +{v}")
    for table in ("concepts", "rules", "evidence", "changes", "curriculum"):
        n = cur.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
        print(f"  total {table}: {n}")
    con.close()


if __name__ == "__main__":
    if "--merge" in sys.argv:
        merge()
    else:
        main()
